function message(key: MessageKey): string {
  if (getLanguage() === 'en') return en[key];
  return (nl as Partial<Record<MessageKey, string>>)[key] ?? en[key];
}

export function t(key: MessageKey): string {
  return message(key);
}

/** For keys built at runtime (e.g. per field or entity type). */
export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/** Replaces `{name}` placeholders. */
export function format(key: MessageKey, vars: Record<string, string | number>): string {
  return message(key).replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
